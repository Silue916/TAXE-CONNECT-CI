-- TaxeConnect CI - MySQL schema (vision v1)
-- Super admin -> mairie admin -> agents -> merchants by commune
CREATE DATABASE IF NOT EXISTS if0_41230418_taxeconnect;
USE if0_41230418_taxeconnect;



CREATE TABLE IF NOT EXISTS communes (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  code VARCHAR(20) NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL UNIQUE,
  department VARCHAR(120) NULL,
  region VARCHAR(120) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS users (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  login VARCHAR(80) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  full_name VARCHAR(160) NULL,
  email VARCHAR(190) NULL UNIQUE,
  phone VARCHAR(30) NULL,
  role ENUM('SUPER_ADMIN','MAIRIE_ADMIN','AGENT','MERCHANT') NOT NULL,
  status ENUM('ACTIVE','INACTIVE') NOT NULL DEFAULT 'ACTIVE',
  commune_id BIGINT UNSIGNED NULL,
  created_by BIGINT UNSIGNED NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_users_commune
    FOREIGN KEY (commune_id) REFERENCES communes(id)
    ON UPDATE CASCADE ON DELETE SET NULL,
  CONSTRAINT fk_users_created_by
    FOREIGN KEY (created_by) REFERENCES users(id)
    ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS mairies (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  commune_id BIGINT UNSIGNED NOT NULL UNIQUE,
  mairie_admin_user_id BIGINT UNSIGNED NOT NULL UNIQUE,
  created_by_super_admin BIGINT UNSIGNED NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_mairies_commune
    FOREIGN KEY (commune_id) REFERENCES communes(id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_mairies_admin_user
    FOREIGN KEY (mairie_admin_user_id) REFERENCES users(id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_mairies_created_by
    FOREIGN KEY (created_by_super_admin) REFERENCES users(id)
    ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS agents (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  commune_id BIGINT UNSIGNED NOT NULL,
  agent_user_id BIGINT UNSIGNED NOT NULL UNIQUE,
  created_by_mairie_admin BIGINT UNSIGNED NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_agents_commune
    FOREIGN KEY (commune_id) REFERENCES communes(id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_agents_user
    FOREIGN KEY (agent_user_id) REFERENCES users(id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_agents_created_by
    FOREIGN KEY (created_by_mairie_admin) REFERENCES users(id)
    ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS merchants (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  merchant_ref VARCHAR(40) NOT NULL UNIQUE,
  user_id BIGINT UNSIGNED NULL UNIQUE,
  commune_id BIGINT UNSIGNED NOT NULL,
  created_by_agent_user_id BIGINT UNSIGNED NOT NULL,
  business_name VARCHAR(180) NOT NULL,
  owner_name VARCHAR(160) NOT NULL,
  phone VARCHAR(30) NULL,
  email VARCHAR(190) NULL,
  activity VARCHAR(160) NULL,
  address TEXT NULL,
  status ENUM('ACTIVE','SUSPENDED','CLOSED') NOT NULL DEFAULT 'ACTIVE',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_merchants_commune
    FOREIGN KEY (commune_id) REFERENCES communes(id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_merchants_user
    FOREIGN KEY (user_id) REFERENCES users(id)
    ON UPDATE CASCADE ON DELETE SET NULL,
  CONSTRAINT fk_merchants_agent
    FOREIGN KEY (created_by_agent_user_id) REFERENCES users(id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  INDEX idx_merchants_commune (commune_id),
  INDEX idx_merchants_activity (activity)
) ENGINE=InnoDB;
